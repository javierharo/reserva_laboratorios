from contextlib import AbstractContextManager
from datetime import date, time
from typing import Protocol

from app.models.entities import Reserva, Usuario
from app.schemas.reservas import ReservaIn


class UsuariosRepository(Protocol):
    def by_email(self, email: str) -> Usuario | None: ...
    def by_id(self, user_id: int) -> Usuario | None: ...
    def add(self, email: str, password_hash: str) -> Usuario: ...


class ReservasRepository(Protocol):
    def atomic(self) -> AbstractContextManager: ...
    def own(self, reserva_id: int, usuario_id: int) -> Reserva | None: ...
    def list_own(self, usuario_id: int, skip: int, limit: int) -> list[Reserva]: ...
    def overlaps(self, laboratorio_id: int, fecha: date, inicio: time, fin: time,
                 excluding: int | None = None) -> bool: ...
    def add(self, usuario_id: int, data: ReservaIn) -> Reserva: ...
    def update(self, reserva: Reserva, data: ReservaIn) -> Reserva: ...
    def delete(self, reserva: Reserva) -> None: ...
